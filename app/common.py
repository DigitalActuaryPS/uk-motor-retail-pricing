"""Shared helpers for the Streamlit app. Simulated data only."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402
import streamlit as st  # noqa: E402

from retailpricing.core import paths  # noqa: E402
from retailpricing.core.config import load_config  # noqa: E402

BANNER = "Simulated data. All customer-level data is generated by code from illustrative assumptions. Not real insurer experience."


def banner() -> None:
    st.warning(BANNER)


def missing_outputs(*names: str) -> bool:
    absent = [n for n in names if not (paths.data_processed() / n).exists()]
    if absent:
        st.info("Pipeline outputs not found: " + ", ".join(absent) + ". Run `make all` first, then reload.")
        return True
    return False


@st.cache_data(show_spinner=False)
def csv(name: str) -> pd.DataFrame:
    return pd.read_csv(paths.data_processed() / name)


@st.cache_data(show_spinner=False)
def js(name: str) -> dict:
    return json.loads((paths.data_processed() / name).read_text())


@st.cache_resource(show_spinner=False)
def config():
    return load_config()


@st.cache_resource(show_spinner="Loading planning book")
def planning_book():
    """Test-period planning book and exact responses. Built once per session."""
    from retailpricing.optimisation.book import PlanningBook
    from retailpricing.optimisation.responses import build_responses
    from retailpricing.optimisation.run import planning_data

    cfg = config()
    nbt, rnt, u_nb, u_rn = planning_data(cfg)
    book = PlanningBook(cfg, nbt, rnt)
    resp = build_responses(cfg, nbt, rnt, u_nb, u_rn, False)
    return book, resp


def pct(v: float, d: int = 1) -> str:
    return f"{v:.{d}%}"
