def main() -> int:
    for name, cells in NOTEBOOKS.items():
        n = nb(cells)
        NotebookClient(n, timeout=600, kernel_name="python3", resources={"metadata": {"path": str(NB_DIR)}}).execute()
        nbf.write(n, NB_DIR / name)
        print("executed", name)
    return 0


