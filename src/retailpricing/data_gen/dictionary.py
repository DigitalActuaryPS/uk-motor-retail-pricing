"""Data dictionary for the simulated quote table."""
from __future__ import annotations

import pandas as pd

ROWS = [
    ("quote_id", "string", "Row key, ordered by quote date"),
    ("quote_date", "datetime", "Date of the quote or renewal offer"),
    ("customer_id", "string", "Anonymised random identifier, one per row"),
    ("business_type", "category", "new_business or renewal"),
    ("channel", "category", "PCW, direct or broker. For renewals, the acquisition channel"),
    ("age_band", "category", "17-24, 25-34, 35-49, 50-64, 65+"),
    ("region", "category", "London_SE, Midlands_East, North_West_Rest"),
    ("pre_existing_risk_band", "category", "low, medium or high input band. Not a modelled outcome"),
    ("tenure", "int", "Years with us at the quote. 0 for new business"),
    ("prior_year_premium", "float", "Previous premium. Renewal rows only"),
    ("our_premium", "float", "Annual premium quoted by us"),
    ("reference_premium", "float", "Premium before any randomised test adjustment"),
    ("comp_min", "float", "Cheapest competitor premium"),
    ("comp_median", "float", "Median competitor premium"),
    ("comp_mean", "float", "Mean competitor premium"),
    ("comp_p1..comp_p8", "float", "Competitor premiums sorted ascending. Used to recompute rank under a price change"),
    ("our_rank", "int", "1 plus the number of competitors cheaper than us"),
    ("price_ratio_to_median", "float", "our_premium / comp_median"),
    ("price_gap_to_cheapest", "float", "our_premium / comp_min - 1"),
    ("treatment_group", "category", "none, control, T-5, T-2, T+2, T+5 (randomised price test, NB only)"),
    ("segment", "category", "age_band|region, 15 segments"),
    ("converted", "int", "1 if a policy is written. For renewal rows this equals renewed"),
    ("renewed_flag", "Int64", "Renewal rows only: 1 renewed, 0 lapsed"),
    ("renewal_outcome", "category", "renewed, lapsed or not_applicable"),
    ("written_premium", "float", "our_premium if converted, else 0"),
    ("unit_cost", "float", "Fixed cost per policy from configuration, converted rows only"),
    ("acquisition_cost", "float", "Fixed per-channel cost on NB policies written"),
    ("fixed_cost_contribution", "float", "written_premium - unit_cost - expense - acquisition_cost, converted rows only"),
    ("data_label", "string", "Always 'Simulated data'"),
]


def data_dictionary() -> pd.DataFrame:
    return pd.DataFrame(ROWS, columns=["field", "type", "description"])


def to_markdown() -> str:
    d = data_dictionary()
    lines = ["# Data dictionary", "", "**Simulated data.** Generated by code. Not real insurer experience.", "",
             "| Field | Type | Description |", "|---|---|---|"]
    lines += [f"| {r.field} | {r.type} | {r.description} |" for r in d.itertuples()]
    lines += ["", "Hidden truth file `data/raw/simulation_truth.parquet` holds `quote_id`, `latent_intent` and `true_probability`. It is used only to validate estimates."]
    return "\n".join(lines) + "\n"
